# Exemplos
idade = 14
altura = 1.55

# Operador and
resultado = (idade > 18) and (altura > 1.78)
print(resultado)

# Operador or
porta = 'a'
janela = 'f'
alarme = (porta == 'a') or (janela == 'a')
print('O alarme foi disparado:',alarme)

# Operador not
tem_dinheiro = False
tem_dinheiro = not tem_dinheiro
mensagem = 'Tem dinheiro? ',tem_dinheiro
print(mensagem)                                                                                                                                      